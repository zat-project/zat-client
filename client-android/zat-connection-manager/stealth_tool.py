_ps = 0

def prngInit(seed):
    global _ps
    _ps = seed

def prngNext():
    global _ps
    # 32-bit arithmetic, then mask to 31 bits
    val = (_ps * 1664525 + 1013904223) & 0xFFFFFFFF
    if val > 0x7FFFFFFF:
        val -= 0x100000000
    _ps = val & 0x7FFFFFFF
    return _ps

def prngNextInt(bound):
    return prngNext() % bound

def decrypt(data):
    n = len(data)
    # Convert to 8-bit unsigned
    b = [x & 0xFF for x in data]
    baseKey = java_hashcode("zat" + _p1 + _p2)
    
    prngInit(_ss)
    swaps = []
    for i in range(n - 1, 0, -1):
        swaps.append((i, prngNextInt(i + 1)))
        
    # Reverse swaps
    for i, j in reversed(swaps):
        b[i], b[j] = b[j], b[i]
        
    # Reverse XOR
    for i in range(n):
        # Java XOR uses signed 32-bit, so baseKey ^ (i * _gr)
        # In Python:
        # i * _gr might overflow 32-bit, so we restrict it to 32-bit signed
        mul = (i * _gr) & 0xFFFFFFFF
        if mul > 0x7FFFFFFF:
            mul -= 0x100000000
        rotKey = (baseKey ^ mul) & 0xFF
        b[i] = (b[i] ^ rotKey) & 0xFF
        
    return bytes(b).decode('utf-8')

def encrypt(text):
    b = list(text.encode('utf-8'))
    n = len(b)
    baseKey = java_hashcode("zat" + _p1 + _p2)
    
    # Forward XOR
    for i in range(n):
        mul = (i * _gr) & 0xFFFFFFFF
        if mul > 0x7FFFFFFF:
            mul -= 0x100000000
        rotKey = (baseKey ^ mul) & 0xFF
        b[i] = (b[i] ^ rotKey) & 0xFF

    prngInit(_ss)
    swaps = []
    for i in range(n - 1, 0, -1):
        swaps.append((i, prngNextInt(i + 1)))
        
    # Forward swaps
    for i, j in swaps:
        b[i], b[j] = b[j], b[i]
        
    return b

